/** Tipo de un reclamo (tipo tipo_reclamo). */
public enum TipoReclamo {
    /** Pregunta o pedido de información. */
    CONSULTA,
    /** Algo no funcionó en la plataforma (error, pago, acceso). */
    INCIDENCIA,
    /** Disconformidad con el servicio recibido (Libro de Reclamaciones). */
    RECLAMO
}
